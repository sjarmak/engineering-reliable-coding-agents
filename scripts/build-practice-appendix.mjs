#!/usr/bin/env node
/**
 * build-practice-appendix.mjs -- generate the in-book practice catalog index.
 *
 * The manuscript names practice records by identifier in every chapter's
 * evidence profile and source sections. Without an index inside the PDF, an
 * ERCA-NNN reference resolved only by leaving the document. This script writes
 * manuscript/appendix-practices.tex from companion/catalog.json, so the index
 * cannot drift from the catalog it indexes, and each row carries the hypertarget
 * that \erca{} links to.
 *
 *     node scripts/build-practice-appendix.mjs [--root .] [--check]
 */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const OUTPUT = path.join("manuscript", "appendix-practices.tex");

/** LaTeX-escape a catalog string. Names are plain prose; no math, no markup. */
export function escapeTex(value) {
  // Catalog names are stored with literal dashes and quotes; the manuscript
  // compiles under a T1 font that has no U+2014 glyph, so normalize first.
  return value
    .replaceAll("\u2014", "---")
    .replaceAll("\u2013", "--")
    .replaceAll("\u2019", "'")
    .replaceAll("\u201c", "``")
    .replaceAll("\u201d", "''")
    .replaceAll("\\", "\\textbackslash{}")
    .replaceAll("&", "\\&")
    .replaceAll("%", "\\%")
    .replaceAll("$", "\\$")
    .replaceAll("#", "\\#")
    .replaceAll("_", "\\_")
    .replaceAll("{", "\\{")
    .replaceAll("}", "\\}")
    .replaceAll("~", "\\textasciitilde{}")
    .replaceAll("^", "\\textasciicircum{}");
}

export function treatmentLabel(record) {
  if (record.treatment === "developed_in_manuscript") return "developed";
  return record.practice_id >= "ERCA-193" && record.thin_support ? "lead" : "companion";
}

export function renderAppendix(records) {
  const sorted = [...records].sort((a, b) => a.practice_id.localeCompare(b.practice_id));
  const developed = sorted.filter((r) => treatmentLabel(r) === "developed").length;
  const leads = sorted.filter((r) => treatmentLabel(r) === "lead").length;
  const companion = sorted.length - developed - leads;
  const limited = sorted.filter((r) => r.thin_support && treatmentLabel(r) !== "lead").length;

  const rows = sorted.map((record) => {
    const id = record.practice_id;
    const anchor = id.toLowerCase();
    const marker = record.thin_support && treatmentLabel(record) !== "lead" ? "\\,$\\dagger$" : "";
    return `\\raisebox{0pt}[0pt][0pt]{\\hypertarget{${anchor}}{}}\\texttt{${id}} & ${escapeTex(record.name)}${marker} & ${record.chapter} & ${treatmentLabel(record)} \\\\`;
  });

  return `% Generated by scripts/build-practice-appendix.mjs from companion/catalog.json.
% Do not edit by hand; run the script and commit its output.
\\chapter{Practice catalog index}\\label{appendix-practices}

Every practice record in this edition carries a stable identifier of the form \\texttt{ERCA-NNN}, after the initials of this book's title. The chapters name records by identifier rather than by title, because a title can be rewritten while the identifier must not be. This index resolves all ${sorted.length} of them: ${developed} developed in the main chapters, ${companion} companion entries, and ${leads} catalog-level leads. Every \\texttt{ERCA-NNN} in the text links to its row here.

The \\emph{chapter} column gives the chapter whose mechanism the record extends, including for records the chapters do not develop. The \\emph{treatment} column separates records developed in the main text from compact companion entries and from leads, which are preserved for investigation rather than recommended. A dagger marks the ${limited} companion entries labeled limited support, where the available evidence does not support a recommendation.

This index carries identity and placement only. The action, mechanism, evidence, and boundary of each record live in the companion artifact, in \\href{https://github.com/sjarmak/engineering-reliable-coding-agents/blob/main/companion/catalog.json}{\\texttt{catalog.json}} and \\href{https://sjarmak.ai/books/engineering-reliable-coding-agents/companion}{the companion site}.

\\begingroup
\\small
\\setlength{\\LTpre}{0.6\\baselineskip}
\\setlength{\\LTpost}{0.6\\baselineskip}
\\begin{longtable}[]{@{}
  >{\\raggedright\\arraybackslash}p{0.145\\linewidth}
  >{\\raggedright\\arraybackslash}p{0.585\\linewidth}
  >{\\raggedright\\arraybackslash}p{0.05\\linewidth}
  >{\\raggedright\\arraybackslash}p{0.135\\linewidth}@{}}
\\caption{Practice catalog index: identifier, practice, chapter, and treatment for all ${sorted.length} records in this edition.}\\tabularnewline
\\toprule\\noalign{}
\\textbf{Identifier} & \\textbf{Practice} & \\textbf{Ch.} & \\textbf{Treatment} \\\\
\\midrule\\noalign{}
\\endfirsthead
\\toprule\\noalign{}
\\textbf{Identifier} & \\textbf{Practice} & \\textbf{Ch.} & \\textbf{Treatment} \\\\
\\midrule\\noalign{}
\\endhead
\\bottomrule\\noalign{}
\\endlastfoot
${rows.join("\n")}
\\end{longtable}
\\endgroup
`;
}

export async function buildAppendix(root, { check = false } = {}) {
  const records = JSON.parse(
    await readFile(path.join(root, "companion", "catalog.json"), "utf8"),
  );
  const rendered = renderAppendix(records);
  const target = path.join(root, OUTPUT);
  const current = await readFile(target, "utf8").catch(() => null);
  if (!check && current !== rendered) await writeFile(target, rendered);
  return { records: records.length, changed: current !== rendered };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const rootFlag = process.argv.indexOf("--root");
  const root = path.resolve(rootFlag >= 0 ? process.argv[rootFlag + 1] : ".");
  const check = process.argv.includes("--check");
  const { records, changed } = await buildAppendix(root, { check });
  if (check && changed) {
    console.log(`${OUTPUT} is out of date; run node scripts/build-practice-appendix.mjs`);
    process.exitCode = 1;
  } else {
    console.log(`${check ? "verified" : "wrote"} ${OUTPUT} with ${records} records`);
  }
}
